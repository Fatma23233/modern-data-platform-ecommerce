SELECT
    COUNT(DISTINCT S.SELLER_ZIP_CODE_PREFIX)
        AS ZIP_SELLERS_SANS_GEO
FROM SILVER.SELLERS S
WHERE NOT EXISTS (
    SELECT 1
    FROM BRONZE.GEOLOCATION_RAW G
    WHERE G.GEOLOCATION_ZIP_CODE_PREFIX =
          S.SELLER_ZIP_CODE_PREFIX
);
SELECT
    (SELECT COUNT(*) FROM BRONZE.CUSTOMERS_RAW)
        AS BRONZE_CUSTOMERS,

    (SELECT COUNT(*) FROM SILVER.CUSTOMERS)
        AS SILVER_CUSTOMERS,

    (SELECT COUNT(*) FROM BRONZE.SELLERS_RAW)
        AS BRONZE_SELLERS,

    (SELECT COUNT(*) FROM SILVER.SELLERS)
        AS SILVER_SELLERS
FROM DUAL;